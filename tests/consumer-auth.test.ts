/** A minimal generated-shaped rules file: role helpers plus the catch-all. */
const RULES = `rules_version = '2';

service cloud.firestore {
  match /databases/{database}/documents {

    // morpheus:begin roles — generated by \`morpheus hq rules\`, do not edit
    function role() {
      return request.auth != null ? request.auth.token.get('role', '') : '';
    }
    // morpheus:end roles

    // Anything not named above is closed. Listed explicitly so that adding a
    // collection is a deliberate act rather than an inherited default.
    match /{document=**} {
      allow read, write: if false;
    }
  }
}
`;

async function fixture(): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), "consumer-auth-"));
  await mkdir(join(root, "apps/web"), { recursive: true });
  await mkdir(join(root, "packages/shared"), { recursive: true });
  await mkdir(join(root, "infra/firebase"), { recursive: true });
  await writeFile(
    join(root, "package.json"),
    `${JSON.stringify({ name: "acme", private: true, scripts: {} }, null, 2)}\n`,
  );
  await writeFile(
    join(root, "apps/web/package.json"),
    `${JSON.stringify(
      { name: "@acme/web", scripts: { test: "node --test" }, dependencies: { next: "16.0.0" } },
      null,
      2,
    )}\n`,
  );
  await writeFile(
    join(root, "packages/shared/package.json"),
    `${JSON.stringify(
      { name: "@acme/shared", exports: { "./schema/waitlist": "./schema/waitlist.ts" } },
      null,
      2,
    )}\n`,
  );
  await writeFile(join(root, "infra/firebase/firestore.rules"), RULES);
  await writeFile(
    join(root, "firebase.json"),
    `${JSON.stringify({ firestore: { rules: "infra/firebase/firestore.rules" } }, null, 2)}\n`,
  );
  await writeFile(join(root, "pnpm-workspace.yaml"), "packages:\n  - apps/*\n  - packages/*\n");
  return root;
}

describe("context derivation", () => {
  it("derives every identifier form from one name", () => {
    expect(slugOf("Heinrich Money")).toBe("heinrich-money");
    expect(camelOf("Heinrich Money")).toBe("heinrichMoney");
    expect(pascalOf("Heinrich Money")).toBe("HeinrichMoney");
    expect(constOf("Heinrich Money")).toBe("HEINRICH_MONEY");
  });

  it("strips a scheme from a domain and keeps a bare host", () => {
    expect(hostOf("https://staging.acme.example")).toBe("staging.acme.example");
    expect(hostOf("acme.example")).toBe("acme.example");
  });

  it("escapes dots in the host pattern", () => {
    // Unescaped, `acme.example` also matches `acmexexample` — the lookalike
    // the known-host allowlist exists to refuse.
    expect(hostPatternOf("acme.example")).toBe("acme\\.example");
  });

  it("computes the schema path relative to the app's test directory", () => {
    expect(sharedSchemaFromTests("apps/web")).toBe("../../../packages/shared/schema/user.ts");
    expect(sharedSchemaFromTests(".")).toBe("../packages/shared/schema/user.ts");
  });
});

describe("template invariants", () => {
  it("keeps the emulator branch dead without the env var", () => {
    // The alg:none acceptance path must be keyed on FIREBASE_AUTH_EMULATOR_HOST
    // read at call time — an attacker-crafted unsigned cookie must never
    // authenticate against a real deployment.
    const rendered = libs.libAuthSessionCookie(ctx);
    expect(rendered).toContain("process.env.FIREBASE_AUTH_EMULATOR_HOST");
    expect(rendered).toContain("emulatorClaims");
  });

  it("anchors the known-host allowlist on both escaped hosts", () => {
    const rendered = libs.libAuthRequestOrigin(ctx);
    expect(rendered).toContain("acme\\.example");
    expect(rendered).toContain("staging\\.acme\\.example");
    expect(rendered).toContain("isKnownAcmeHost");
  });

  it("builds the reset route's constant answer per call, not at module scope", () => {
    // A module-level NextResponse body is a one-shot stream: first caller gets
    // {"ok":true}, everyone after an empty body — an enumeration oracle built
    // out of a caching mistake. Found on Evo by asking three times.
    const rendered = app.apiResetPasswordRoute(ctx);
    expect(rendered).toContain("function accepted()");
    expect(rendered).not.toMatch(/const accepted = NextResponse/);
  });

  it("mints the session only after the CSRF origin check", () => {
    const rendered = app.apiAuthSessionRoute(ctx);
    expect(rendered.indexOf("isSameOrigin")).toBeGreaterThan(-1);
    expect(rendered.indexOf("isSameOrigin")).toBeLessThan(rendered.indexOf("createSessionCookie"));
  });

  it("keeps the hint cookie readable and the session cookie httpOnly", () => {
    const rendered = app.apiAuthSessionRoute(ctx);
    expect(rendered).toContain("httpOnly: true");
    expect(rendered).toContain("httpOnly: false");
    // The name itself lives in the config, prefixed per project.
    expect(libs.libFirebaseConfig(ctx)).toContain('"acme_signed_in"');
  });

  it("checks deliverability before generating an action code", () => {
    // Generating revokes the outstanding code of the same type, so
    // generate-then-fail-to-send kills the link already in the inbox.
    const rendered = libs.libAuthSendActionEmail(ctx);
    expect(rendered.indexOf("canDeliver()")).toBeLessThan(
      rendered.indexOf("generateEmailVerificationLink"),
    );
  });

  it("points the E2E helper at the project the client bundle resolves", () => {
    // The exec project must match the bundle's (staging, since VERCEL_ENV is
    // absent at build time) or the Auth emulator splits one logical account
    // across two project ids.
    expect(suites.e2eEmulatorHelper(ctx)).toContain('PROJECT_ID = "ac-acme-staging"');
    expect(rootScriptSet(survey, ctx)["test:e2e"]).toContain("--project ac-acme-staging");
  });

  it("round-trips both environments through the config parser", () => {
    const facts = parseTwoEnvFacts(libs.libFirebaseConfig(ctx));
    expect(facts.production).toEqual(ctx.production);
    expect(facts.staging).toEqual(ctx.staging);
    expect(facts.workloadIdentity).toEqual(ctx.workloadIdentity);
  });
});

describe("scaffoldConsumerAuth", () => {
  let root: string;

  beforeEach(async () => {
    root = await fixture();
  });

  it("writes the plan, and a second run changes nothing", async () => {
    const first = await scaffoldConsumerAuth({ root, survey, ctx });
    expect(first.written.length).toBe(plannedFiles(survey, ctx).length);
    expect(first.drifted).toEqual([]);

    const second = await scaffoldConsumerAuth({ root, survey, ctx });
    expect(second.written).toEqual([]);
    expect(second.drifted).toEqual([]);
    expect(second.merged).toEqual([]);
  });

  it("never overwrites, and names a drifted plumbing file", async () => {
    const path = join(root, "apps/web/lib/auth/safe-next.ts");
    await mkdir(join(root, "apps/web/lib/auth"), { recursive: true });
    await writeFile(path, "// locally edited\n");

    const result = await scaffoldConsumerAuth({ root, survey, ctx });
    expect(result.drifted).toContain("apps/web/lib/auth/safe-next.ts");
    expect(await readFile(path, "utf8")).toBe("// locally edited\n");
  });

  it("inserts the consumer rules inside the service scope, above the catch-all", async () => {
    await scaffoldConsumerAuth({ root, survey, ctx });
    const rules = await readFile(join(root, "infra/firebase/firestore.rules"), "utf8");

    const users = rules.indexOf("match /users/{uid}");
    const catchAll = rules.indexOf("match /{document=**}");
    expect(users).toBeGreaterThan(-1);
    expect(users).toBeLessThan(catchAll);
    // Still exactly one catch-all, and the block landed before the closing
    // braces rather than after them.
    expect(rules.match(/match \/\{document=\*\*\}/g)).toHaveLength(1);
    expect(rules.trimEnd().endsWith("}")).toBe(true);

    // Idempotent: the presence check, not the anchor, decides on a re-run.
    const again = await addConsumerRules(root, "infra/firebase/firestore.rules");
    expect(again.kind).toBe("none");
  });

  it("refuses to write rules at a guessed position", async () => {
    await writeFile(
      join(root, "infra/firebase/firestore.rules"),
      "rules_version = '2';\nservice cloud.firestore {}\n",
    );
    const outcome = await addConsumerRules(root, "infra/firebase/firestore.rules");
    expect(outcome.kind).toBe("note");
  });

  it("merges the emulators block and leaves foreign ports alone", async () => {
    await scaffoldConsumerAuth({ root, survey, ctx });
    const parsed = JSON.parse(await readFile(join(root, "firebase.json"), "utf8")) as {
      emulators?: { auth?: { port?: number }; firestore?: { port?: number } };
    };
    // The rules suite dials these literally; a default that moved would make
    // it hang rather than fail.
    expect(parsed.emulators?.auth?.port).toBe(9099);
    expect(parsed.emulators?.firestore?.port).toBe(8080);

    await writeFile(
      join(root, "firebase.json"),
      JSON.stringify({ emulators: { auth: { port: 9199 }, firestore: { port: 8081 } } }),
    );
    const outcome = await ensureEmulatorsBlock(root, "infra/firebase/firestore.rules");
    expect(outcome.kind).toBe("note");
  });

  it("writes a .firebaserc with no default alias", async () => {
    // `firebase deploy` with no --project uses the default alias; leaving it
    // out means a stray deploy asks instead of silently picking production.
    await scaffoldConsumerAuth({ root, survey, ctx });
    const parsed = JSON.parse(await readFile(join(root, ".firebaserc"), "utf8")) as {
      projects: Record<string, string>;
    };
    expect(parsed.projects["default"]).toBeUndefined();
    expect(parsed.projects["prod"]).toBe("ac-acme");
    expect(parsed.projects["staging"]).toBe("ac-acme-staging");
  });

  it("merges root scripts and the shared export", async () => {
    await scaffoldConsumerAuth({ root, survey, ctx });

    const rootPkg = JSON.parse(await readFile(join(root, "package.json"), "utf8")) as {
      scripts: Record<string, string>;
      devDependencies: Record<string, string>;
    };
    expect(rootPkg.scripts["test:emulator"]).toContain("emulators:exec");
    expect(rootPkg.scripts["test:e2e"]).toContain("build:e2e");
    expect(rootPkg.devDependencies["@firebase/rules-unit-testing"]).toBeTruthy();

    const shared = JSON.parse(
      await readFile(join(root, "packages/shared/package.json"), "utf8"),
    ) as { exports: Record<string, string> };
    expect(shared.exports["./schema/user"]).toBe("./schema/user.ts");
  });

  it("check reports clean after a scaffold, and drift after an edit", async () => {
    await scaffoldConsumerAuth({ root, survey, ctx });
    expect(await checkConsumerAuth({ root, survey, ctx })).toBe(0);

    await writeFile(join(root, "apps/web/lib/auth/request-origin.ts"), "// edited\n");
    expect(await checkConsumerAuth({ root, survey, ctx })).toBe(1);
  });
});
