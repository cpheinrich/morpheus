#!/usr/bin/env node
// Propagate the canonical product/design skills from .agents/skills to their Claude mirrors and
// to src/product/skill.ts, which `morpheus product guide` prints.
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";

const root = join(import.meta.dirname, "..");
const skills = [
  {
    name: "chief-product-officer",
    constant: "CHIEF_PRODUCT_OFFICER_SKILL",
    accessor: "chiefProductOfficerSkillFiles",
    summary: "The Chief Product Officer skill: product outcomes, evidence, priorities and acceptance.",
  },
  {
    name: "vp-design",
    constant: "VP_DESIGN_SKILL",
    accessor: "vpDesignSkillFiles",
    summary: "The VP of Design skill under the CPO: experience quality and design-system coherence.",
  },
];

async function filesUnder(dir) {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true }).catch((error) => {
    if (error.code === "ENOENT") return [];
    throw error;
  });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => relative(dir, join(entry.parentPath, entry.name)).split("\\").join("/"));
}

const literal = (text) =>
  text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

async function sync({ name, constant, accessor, summary }) {
  const canonical = join(root, ".agents/skills", name);
  const mirror = join(root, ".claude/skills", name);
  const files = (await filesUnder(canonical)).sort((left, right) =>
    left === "SKILL.md" ? -1 : right === "SKILL.md" ? 1 : left.localeCompare(right),
  );
  if (!files.includes("SKILL.md")) throw new Error(`${canonical}/SKILL.md is missing`);

  const contents = Object.fromEntries(
    await Promise.all(files.map(async (file) => [file, await readFile(join(canonical, file), "utf8")])),
  );

  for (const stale of (await filesUnder(mirror)).filter((file) => !files.includes(file))) {
    await rm(join(mirror, stale));
  }
  for (const [file, content] of Object.entries(contents)) {
    await mkdir(dirname(join(mirror, file)), { recursive: true });
    await writeFile(join(mirror, file), content);
  }

  const entries = Object.entries(contents)
    .map(([file, content]) => `  ${JSON.stringify(file)}: \`${literal(content)}\`,\n`)
    .join("");
  console.log(`Synced ${name}, ${files.length} file(s): ${files.join(", ")}`);
  return (
    `/** ${summary} */\n` +
    `export const ${constant} = ${JSON.stringify(name)};\n\n` +
    `export const ${accessor} = (): Record<string, string> => ({\n${entries}});\n`
  );
}

const sections = [];
for (const skill of skills) sections.push(await sync(skill));

await mkdir(join(root, "src/product"), { recursive: true });
await writeFile(
  join(root, "src/product/skill.ts"),
  `/**
 * Product-leadership skills requested in MO-26-10-29-11.07.29. Morpheus holds the canonical files,
 * \`morpheus product guide\` prints them, and managed projects carry one-file pointers.
 *
 * Generated by scripts/sync-product-skills.mjs from .agents/skills/<skill>.
 */
${sections.join("\n")}`,
);
