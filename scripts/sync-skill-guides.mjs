#!/usr/bin/env node
// Canonical guide skills are edited in .agents; the Claude mirror and CLI bytes are derived, never authored.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

const GUIDES = [
  { name: "visual-design", module: "src/design/visual-design.ts", constant: "VISUAL_DESIGN_SKILL" },
  { name: "morpheus-swift-packages", module: "src/swift-packages/skill.ts", constant: "SWIFT_PACKAGES_SKILL" },
];

const root = join(import.meta.dirname, "..");
for (const { name, module, constant } of GUIDES) {
  const skill = await readFile(join(root, `.agents/skills/${name}/SKILL.md`), "utf8");
  await mkdir(join(root, `.claude/skills/${name}`), { recursive: true });
  await writeFile(join(root, `.claude/skills/${name}/SKILL.md`), skill);
  await mkdir(dirname(join(root, module)), { recursive: true });
  await writeFile(
    join(root, module),
    `/** Generated by scripts/sync-skill-guides.mjs from the canonical .agents skill. */\n` +
      `export const ${constant} = ${JSON.stringify(skill)};\n`,
  );
}
