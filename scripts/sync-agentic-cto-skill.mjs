#!/usr/bin/env node
// Propagate an edit of the canonical skills in .agents/skills — agentic-cto and the
// individual-contributor skills under it — to their Claude mirrors and to src/cto/skill.ts, which
// the CLI prints with `morpheus cto guide`. Run from anywhere:
//
//   node scripts/sync-agentic-cto-skill.mjs
//
// tests/agentic-cto-skill.test.ts fails until every copy agrees, so this only saves the
// hand-escaping of backticks and `${` inside a template literal.
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";

const root = join(import.meta.dirname, "..");

/** Each skill the module carries, in the order it is written. */
const SKILLS = [
  { name: "agentic-cto", constant: "AGENTIC_CTO_SKILL", accessor: "agenticCtoSkillFiles" },
  {
    name: "research-engineer",
    constant: "RESEARCH_ENGINEER_SKILL",
    accessor: "researchEngineerSkillFiles",
    summary:
      "The research-engineer skill (MO-26-10-23-00.08.15): hands-on ML and algorithm research, as the\n" +
      " * first individual-contributor skill under the agentic CTO.",
  },
];

async function filesUnder(dir) {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true }).catch((error) => {
    if (error.code === "ENOENT") return [];
    throw error;
  });
  return entries.filter((e) => e.isFile()).map((e) => relative(dir, join(e.parentPath, e.name)).split("\\").join("/"));
}

const literal = (s) => s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

/** Mirror one skill into .claude/skills and return its module source. */
async function sync({ name, constant, accessor, summary }) {
  const canonical = join(root, ".agents/skills", name);
  const mirror = join(root, ".claude/skills", name);
  const files = (await filesUnder(canonical)).sort((a, b) =>
    a === "SKILL.md" ? -1 : b === "SKILL.md" ? 1 : a.localeCompare(b),
  );
  if (!files.includes("SKILL.md")) throw new Error(`${canonical}/SKILL.md is missing`);

  const contents = Object.fromEntries(
    await Promise.all(files.map(async (f) => [f, await readFile(join(canonical, f), "utf8")])),
  );

  for (const stale of (await filesUnder(mirror)).filter((f) => !files.includes(f))) {
    await rm(join(mirror, stale));
  }
  for (const [file, content] of Object.entries(contents)) {
    await mkdir(dirname(join(mirror, file)), { recursive: true });
    await writeFile(join(mirror, file), content);
  }

  const entries = Object.entries(contents)
    .map(([file, content]) => `  ${JSON.stringify(file)}: \`${literal(content)}\`,\n`)
    .join("");
  console.log(`Synced ${name}, ${files.length} file(s): ${files.join(", ")}`);
  return (
    (summary ? `/**\n * ${summary}\n */\n` : "") +
    `export const ${constant} = ${JSON.stringify(name)};\n\n` +
    `export const ${accessor} = (): Record<string, string> => ({\n${entries}});\n`
  );
}

const sections = [];
for (const skill of SKILLS) sections.push(await sync(skill));

await writeFile(
  join(root, "src/cto/skill.ts"),
  `/**
 * The agentic-CTO skill (MO-26-10-21-19.17.32): how an agent runs a delegated outcome under an
 * explicit, written mandate and budget. Morpheus holds the one canonical copy; the CLI prints it
 * with \`morpheus cto guide\`, and every other project's skill points there. The
 * individual-contributor skills under it follow below, the same way.
 *
 * Generated by scripts/sync-agentic-cto-skill.mjs from .agents/skills/<skill> — edit those files
 * and re-run it. Each skill is keyed by path inside its directory.
 */
${sections.join("\n")}`,
);
