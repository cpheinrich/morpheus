#!/usr/bin/env node
// The canonical skill is edited in .agents; mirror and CLI bytes are derived, never authored.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const skill = await readFile(join(root, ".agents/skills/visual-design/SKILL.md"), "utf8");
await mkdir(join(root, ".claude/skills/visual-design"), { recursive: true });
await writeFile(join(root, ".claude/skills/visual-design/SKILL.md"), skill);
await writeFile(
  join(root, "src/design/visual-design.ts"),
  `/** Generated by scripts/sync-visual-design-skill.mjs from the canonical .agents skill. */\n` +
    `export const VISUAL_DESIGN_SKILL = ${JSON.stringify(skill)};\n`,
);
